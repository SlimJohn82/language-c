/**
 * Output (Print text)
Pour afficher des valeurs ou imprimer du texte en C, vous pouvez utiliser la printf()fonction :
 */

#include <stdio.h>
int main()
{
	printf("Hello World");
	return 0;
}

/**
 * Double Quotes:
Pour imprimer du texte, celui-ci doit être placé entre guillemets doubles "".
Si vous oubliez les guillemets, une erreur se produit :
 */

/**
 * Many printf () Functions
 Vous pouvez utiliser autant printf()de fonctions que vous le souhaitez.
Notez toutefois qu'il n'insère pas de nouvelle ligne à la fin du résultat :
 */

#include <stdio.h>
int main()
{
	printf("Hello World");
	printf("I am a Learning C");
	printf("And it in awsome!");
	return 0;
}
